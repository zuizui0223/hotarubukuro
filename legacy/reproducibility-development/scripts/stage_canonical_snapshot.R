  magic <- readBin(archive, what = "raw", n = 2L)
  if (length(magic) != 2L || magic[[1L]] != as.raw(0x50) ||
      magic[[2L]] != as.raw(0x4b)) {
    note_failure(
      basename(archive),
      " is not a zip archive; a provider error page was probably saved."
    )
  }
}

