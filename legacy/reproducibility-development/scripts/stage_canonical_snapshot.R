check_table <- function(path, required_columns, label, unique_site_id = FALSE) {
  if (!file.exists(path)) {
    note_failure("missing ", label, ": ", path)
    return(NULL)
  }
  table <- utils::read.csv(
    path, check.names = FALSE, stringsAsFactors = FALSE
  )
  absent <- setdiff(required_columns, names(table))
  if (length(absent)) {
    note_failure(
      label, " is missing required columns: ",
      paste(absent, collapse = ", ")
    )
  }
  if (!nrow(table)) note_failure(label, " is empty.")
  if (all(c("longitude", "latitude") %in% names(table))) {
    if (anyNA(table$longitude) || anyNA(table$latitude)) {
      note_failure(label, " has missing coordinates.")
    } else if (min(table$longitude) < 122 || max(table$longitude) > 154 ||
               min(table$latitude) < 24 || max(table$latitude) > 46) {
      note_failure(label, " has coordinates outside the Japanese study window.")
    }
  }
  # exact_site_id is the cell key in the cell table, where it must be unique,
  # but a site key in the observation-level phenotype table, where repeats are
  # the normal case of several flowers recorded at one site.
  if (unique_site_id && "exact_site_id" %in% names(table) &&
      anyDuplicated(table$exact_site_id)) {
    note_failure(label, " has duplicate exact_site_id values.")
  }
  table
}

observations <- check_table(
  observations_path, required_observation_columns, "phenotype analysis table"
)
cells <- check_table(
  cells_path, required_cell_columns, "1-km cell table", unique_site_id = TRUE
)
if (!is.null(cells)) {
  if (!all(cells$spatial_unit_km == 1)) {
    note_failure("the cell table is not the 1-km table.")
  }
  if (any(!is.finite(cells$n_observations)) || any(cells$n_observations < 1)) {
    note_failure("every cell must carry at least one observation.")
  }
  if (any(cells$n_pigmented < 0) ||
      any(cells$n_pigmented > cells$n_observations)) {
    note_failure("pigmented counts fall outside [0, n_observations].")
  }
}

# Supplying established tables is only useful if they are the established ones.
# A near-miss — a rerun, a partial export, the reconstruction copied by mistake —
# would otherwise be published under a name that says "as in the manuscript", so
# the counts are checked against the committed expectations before staging.
if (use_established) {
  if (!file.exists(expectations_path)) {
    note_failure(
      "--established-inputs was given but ", expectations_path, " is missing, ",
      "so the supplied tables cannot be confirmed as the published ones."
    )
  } else {
    expectations <- utils::read.csv(
      expectations_path, check.names = FALSE, stringsAsFactors = FALSE
    )
    expected_of <- function(quantity) {
      value <- expectations$expectation[expectations$quantity == quantity]
      if (!length(value)) NA_real_ else as.numeric(value[[1L]])
    }
    if (!is.null(observations)) {
      expected_n <- expected_of("analysis_observations")
      if (!is.na(expected_n) && nrow(observations) != expected_n) {
        note_failure(
          "the supplied phenotype table has ", nrow(observations),
          " rows but the published analysis has ", expected_n,
          ". These are not the established analysis inputs; see ",
          "docs/established-inputs.md."
        )
      }
    }
    measurement_path <- file.path(
      phenotype_source, "pigmentation_measurement_summary.csv"
    )
    if (!file.exists(measurement_path)) {
      note_failure(
        "the supplied phenotype directory has no ",
        "pigmentation_measurement_summary.csv; the whole stage directory is ",
        "needed, not only the analysis table."
      )
    } else {
      measurement <- utils::read.csv(
        measurement_path, check.names = FALSE, stringsAsFactors = FALSE
      )
      for (pair in list(
        c("white_observations", "n_white"),
        c("pigmented_observations", "n_pigmented")
      )) {
        expected_value <- expected_of(pair[[1L]])
        observed_value <- if (pair[[2L]] %in% names(measurement)) {
          as.numeric(measurement[[pair[[2L]]]][[1L]])
        } else {
          NA_real_
        }
        if (!is.na(expected_value) &&
            (is.na(observed_value) || observed_value != expected_value)) {
          note_failure(
            "the supplied measurement summary reports ", pair[[2L]], "=",
            observed_value, " but the published analysis has ", expected_value,
            "."
          )
        }
      }
    }
  }

  # The regenerated tables are not discarded. Whatever this run rebuilt from the
  # public sources is compared against what is being staged, so the snapshot
  # ships with an explicit record of how far the reproducible route lands from
  # the published one.
  regenerated_path <- file.path(
    results_root, "ecological_v11_pigmentation_hurdle",
    "analysis_data_pigmentation_hurdle.csv"
  )
  divergence <- data.frame(
    quantity = "analysis_observations",
    established = if (is.null(observations)) NA_integer_ else nrow(observations),
    regenerated = if (file.exists(regenerated_path)) {
      nrow(utils::read.csv(
        regenerated_path, check.names = FALSE, stringsAsFactors = FALSE
      ))
    } else {
      NA_integer_
    },
    stringsAsFactors = FALSE
  )
  divergence$difference <- divergence$regenerated - divergence$established
  message("[snapshot] established versus regenerated analysis inputs:")
  print(divergence, row.names = FALSE)
}

